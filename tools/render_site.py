#!/usr/bin/env python3
"""Render the five-language introduction site. Never modifies ranking data."""
from __future__ import annotations
import argparse
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = 'https://jammyfu.github.io/github-risers/'
REPO = 'https://github.com/jammyfu/github-risers'
LANGS = {'en': 'English', 'zh-Hans': '简体中文', 'zh-Hant': '繁體中文', 'ja': '日本語', 'ko': '한국어'}
DOCS = ['docs/FACTS.md', 'docs/FAQ.md', 'docs/CATEGORIES.md', 'docs/NEW_ARRIVALS.md', 'docs/DAILY_UPDATE.md']
CSS = '''*{box-sizing:border-box}body{margin:0;font:16px/1.65 system-ui,-apple-system,"Segoe UI",sans-serif;color:#1b1f2a;background:#f6f7fb;overflow-wrap:anywhere}
header{background:linear-gradient(135deg,#0f172a,#312e81 55%,#7c3aed);color:#fff;padding:40px 20px}.w{max-width:860px;margin:0 auto}h1{margin:0 0 12px;font-size:clamp(1.7rem,5vw,2.2rem);line-height:1.2}header p{color:#e5e7ff}a.btn{display:inline-block;padding:10px 18px;border-radius:8px;background:#fff;color:#312e81;text-decoration:none;font-weight:600}.hero{display:block;max-width:100%;height:auto;margin:24px auto 0;border-radius:12px}
main{padding:12px 20px 40px}h2{margin-top:32px;font-size:1.35rem}table{border-collapse:collapse;width:100%;background:#fff}td,th{border:1px solid #e3e5ee;padding:8px 12px;text-align:left;vertical-align:top}th{width:25%;background:#eef0f8}details{background:#fff;border:1px solid #e3e5ee;border-radius:8px;padding:10px 14px;margin:8px 0}summary{cursor:pointer;font-weight:600}a{color:#4338ca}ul{padding-left:1.2em}footer{padding:24px 20px 40px;color:#555;font-size:.9rem}.sw{display:flex;flex-wrap:wrap;gap:8px 16px;margin:18px 0}.sw a{color:#e0e7ff}a:focus-visible,summary:focus-visible{outline:3px solid #fb923c;outline-offset:4px}@media(max-width:480px){header,main,footer{padding-left:16px;padding-right:16px}td,th{padding:8px}}
'''

def page_url(lang):
    return BASE + ('' if lang == 'en' else lang + '/')

def readme_url(lang):
    return REPO + ('#readme' if lang == 'en' else '/blob/main/README.' + lang + '.md')

def render(lang, s):
    e = html.escape
    url = page_url(lang)
    alternates = '\n'.join(f'<link rel="alternate" hreflang="{code}" href="{page_url(code)}">' for code in LANGS)
    schema = [
        {'@context': 'https://schema.org', '@type': 'Dataset', 'name': s['title'], 'description': s['description'], 'url': url, 'sameAs': REPO, 'license': 'https://opensource.org/license/mit', 'isAccessibleForFree': True, 'inLanguage': list(LANGS), 'creator': {'@type':'Person','name':'jammyfu','url':'https://github.com/jammyfu'}, 'variableMeasured':['stars','stars gained per day'], 'distribution':[{'@type':'DataDownload','encodingFormat':'application/json','contentUrl':'https://raw.githubusercontent.com/jammyfu/github-risers/main/data/stats.json'}]},
        {'@context':'https://schema.org','@type':'SoftwareSourceCode','name':'github-risers','codeRepository':REPO,'programmingLanguage':'Python','license':'https://opensource.org/license/mit'},
        {'@context':'https://schema.org','@type':'FAQPage','inLanguage':lang,'mainEntity':[{'@type':'Question','name':q,'acceptedAnswer':{'@type':'Answer','text':a}} for q,a in s['faq']]},
    ]
    scripts='\n'.join('<script type="application/ld+json">'+json.dumps(x,ensure_ascii=False).replace('<','\\u003c')+'</script>' for x in schema)
    nav=''.join(f'<a href="{page_url(code)}" hreflang="{code}"'+(' aria-current="page"' if code==lang else '')+f'>{label}</a>' for code,label in LANGS.items())
    rows=''.join(f'<tr><th scope="row">{e(k)}</th><td>{e(v)}</td></tr>' for k,v in s['facts'])
    rankings=''.join(f'<li><a href="{readme_url(code)}" hreflang="{code}">{label}</a></li>' for code,label in LANGS.items())
    faq=''.join(f'<details><summary>{e(q)}</summary><p>{e(a)}</p></details>' for q,a in s['faq'])
    links=[REPO+'/blob/main/'+p for p in DOCS]+['https://raw.githubusercontent.com/jammyfu/github-risers/main/data/stats.json',BASE+'llms.txt',REPO]
    docs=''.join(f'<li><a href="{u}">{e(label)}</a></li>' for u,label in zip(links,s['docs']))
    intro=''.join('<p>'+e(x)+'</p>' for x in s['intro'])
    headings=[e(x) for x in s['headings']]
    return f'''<!doctype html>
<!-- Generated by tools/render_site.py; edit tools/site_locales.json instead. -->
<html lang="{lang}"><head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{e(s['title'])}</title><meta name="description" content="{e(s['description'])}">
<link rel="canonical" href="{url}">
{alternates}
<link rel="alternate" hreflang="x-default" href="{BASE}">
<meta property="og:type" content="website"><meta property="og:title" content="{e(s['title'])}"><meta property="og:description" content="{e(s['description'])}"><meta property="og:url" content="{url}">
<meta property="og:image" content="https://raw.githubusercontent.com/jammyfu/github-risers/main/.github/social-preview.png"><meta name="twitter:card" content="summary_large_image">
<style>{CSS}</style>
{scripts}
</head><body><header><div class="w">
<h1>{e(s['h1'])}</h1>{intro}
<a class="btn" href="{readme_url(lang)}">{e(s['cta'])}</a>
<nav class="sw" aria-label="Language">{nav}</nav>
<img class="hero" src="https://raw.githubusercontent.com/jammyfu/github-risers/main/.github/social-preview.png" width="640" alt="GitHub Risers">
</div></header><main><div class="w">
<h2>{headings[0]}</h2><table>{rows}</table>
<h2>{headings[1]}</h2><ul>{rankings}</ul>
<h2>{headings[2]}</h2>{faq}
<h2>{headings[3]}</h2><ul>{docs}</ul>
</div></main><footer><div class="w">{e(s['footer'])}</div></footer></body></html>
'''

def outputs():
    locales=json.loads((ROOT/'tools/site_locales.json').read_text('utf-8'))
    result={Path('docs')/('' if code=='en' else code)/'index.html':render(code,locales[code]) for code in LANGS}
    alternate=''.join(f'<xhtml:link rel="alternate" hreflang="{c}" href="{page_url(c)}"/>' for c in LANGS)+f'<xhtml:link rel="alternate" hreflang="x-default" href="{BASE}"/>'
    result[Path('docs/sitemap.xml')]='<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'+''.join(f'<url><loc>{page_url(c)}</loc>{alternate}</url>\n' for c in LANGS)+'</urlset>\n'
    result[Path('docs/llms.txt')]=(ROOT/'llms.txt').read_text('utf-8')
    return result

def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args(argv)
    stale=[]
    for path,content in outputs().items():
        target=ROOT/path
        if args.check:
            if not target.exists() or target.read_text('utf-8')!=content: stale.append(str(path))
        else:
            target.parent.mkdir(parents=True,exist_ok=True);target.write_text(content,encoding='utf-8')
    if stale:
        print('Stale site files: '+', '.join(stale));return 1
    return 0

if __name__=='__main__':
    raise SystemExit(main())
